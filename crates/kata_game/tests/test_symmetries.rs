fn run_mark_duplicate_test(
    board: &Board,
    pla: i8,
    only_symmetries: Option<&[i32]>,
    out: &mut String,
) {
    let hist = BoardHistory::new(board.clone(), pla, Rules::get_tromp_taylorish(), 0);
    let (is_sym_dup_loc, valid_symmetries) =
        kata_game::symmetry::mark_duplicate_move_locs(board, &hist, only_symmetries, &[]);

    out.push_str(&board.to_string_simple('\n'));
    out.push_str("Symmetries:");
    for &symmetry in &valid_symmetries {
        out.push_str(&format!(" {symmetry}"));
    }
    out.push('\n');

    for y in 0..board.y_size {
        for x in 0..board.x_size {
            let loc = location::get_loc(x, y, board.x_size);
            if is_sym_dup_loc[loc as usize] {
                out.push('x');
            } else {
                out.push('.');
            }
        }
        out.push('\n');
    }
    out.push('\n');
}
