fn format_symmetry_differences(
    board: &Board,
    other: &Board,
    max_difference: f64,
    out: &mut String,
) {
    let diffs = kata_game::symmetry::get_symmetry_differences(board, other, max_difference);
    out.push_str(&format!(
        "{:.1} {:.1} {:.1} {:.1} {:.1} {:.1} {:.1} {:.1}\n",
        diffs[0], diffs[1], diffs[2], diffs[3], diffs[4], diffs[5], diffs[6], diffs[7]
    ));
}

